export function featuresToFormData(features: Partial<FeatureMap>): Record<string, boolean> {
    const map: Record<string, boolean> = {};
    if (features.hasLogin) map.hasAccounts = true;
    if (features.hasPayments) map.sellsProducts = true;
    if (features.hasSubscriptions) map.hasSubscriptions = true;
    if (features.hasUserGeneratedContent) map.userGeneratedContent = true;
    if (features.hasAiFeatures) map.usesAi = true;
    if (features.hasCookiesAnalytics) map.usesCookies = true;
    if (features.hasNewsletter) map.hasNewsletter = true;
    if (features.hasBookingSystem) map.hasBookingSystem = true;
    return map;
}